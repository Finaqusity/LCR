section = """### 2.4 电源纹波与去耦（9 V 升压 + 3.3 V 参考）

**三道"免费 immunity"**

1. **比率测量**：结果 = Vo/Vin，两路共有的量（电源纹波、基准漂移、ADC 基准噪声）在除法里抵消。
2. **双通道同一颗 ADC、同一时刻采样**：VREF 噪声对两路同乘一个系数，比率里抵消；采样时刻一致（TIM2 TRGO），纹波不会变成假相位。
3. **DFT 只取 f0 一个 bin**：等效带宽 ≈ fs/N ≈ 1.5 kHz（fs = 1.6 MHz、N = 1024），开关纹波与白噪声大多落在带外。

**噪声路径与衰减**

| 噪声路径 | 典型量级 | 到结果的衰减 | 等效误差 |
|---|---|---|---|
| +9V（MT3608，约 1.2 MHz） | 20–50 mVpp | 运放 PSRR 约 60 dB + 去耦 | ~20 µV → **0.004%** |
| +5V（USB / 适配器） | 50–100 mVpp | 只供数字与继电器；AD9833 经 3.3VA LDO（PSRR 70 dB@1 kHz） | **≈0** |
| VREF_AFE 纹波 | 10–100 µVrms | 两路共有 → 只有在 f0 处才成误差 | 见下 |
| ADC 的 VREF+ 噪声 | 约 1 mVrms | 双通道共用，比率抵消 | **≈0** |
| 继电器动作地弹 | 10–50 mV 脉冲 | 等 5–10 ms 再采 | **≈0** |
| 市电 100 Hz（变压器电源） | 100 mVpp | 参考缓冲 PSRR ≈ 100 dB → 约 1 µV | **≈0**；但直接耦合到夹具才危险 |

**唯一要防的一类**：频率正好等于 f0 的干扰（测 100 Hz 时最典型），DFT 滤不掉。此时

```
ΔZ/Z ≈ (1 + 1/G)·ε/Vin ，G = |Vo|/|Vin|
```

G ≈ 1 时约为"干扰/信号"的 2 倍。守 0.5% 需 f0 处干扰 < 0.25% × 0.5 Vrms ≈ **1.2 mVrms**；参考点缓冲后通常只有几十 µV，余量 20 倍以上。

**五个做法**

1. 参考点必须缓冲（3.3VA → 10 Ω → 10 µF∥100 nF → OPA2810-B 跟随），不能拿分压电阻直接当参考。
2. 每个运放电源脚 10 µF + 100 nF；+9V 进 AFE 前加 10 Ω + 22 µF。
3. MT3608 的开关回路（输入电容、电感、二极管、IC 地）只走数字区，离 AFE ≥10 mm；L3 不在 AFE 下方走 +5V/+9V 大电流。
4. 继电器续流就近（ULN2803 内置 + 外部 1N4148），线圈电流只在数字侧闭合。
5. 切档/切频后留 5–10 ms 稳定期再开 DMA。

**三条验收**

1. 示波器 AC 耦合、1 mV/div、20 MHz 带宽限制，测 VREF_AFE 对 AGND → **< 1 mVpp**。
2. 100 Hz、0.5 Vrms 时看 TP1 包络有没有"呼吸"→ 有则低频纹波进了激励环路。
3. 同一只 1 kΩ 电阻，USB 供电与外部适配器供电各测 10 次，读数散布 **< 0.05%**。

**结论**：按 9 V + 3.3 V 缓冲参考 + 逐脚去耦 + 数字/模拟分区，电源纹波在误差预算里只占 0.05% 量级（不到 1%）；真正的瓶颈是夹具杂散稳定性、通道增益失配、100 kHz 相位。

---

## 3. 接地"""
